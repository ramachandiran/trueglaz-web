/**
 * Generates the web app's CSS custom properties from the shared token file.
 *
 * React Native cannot read CSS variables, so packages/core/src/theme/tokens.ts
 * is the single source of truth and this writes the web half of it. The web
 * stylesheets keep using var(--tg-*) exactly as before — they just no longer
 * hold any colour of their own.
 *
 *   npm run tokens
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { register } from 'node:module'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

// tokens.ts is TypeScript; strip the types rather than add a build step for one file.
register('data:text/javascript,' +
  encodeURIComponent(`
    import { readFileSync } from 'node:fs'
    import { fileURLToPath } from 'node:url'
    export async function load(url, context, next) {
      if (url.endsWith('.ts')) {
        const src = readFileSync(fileURLToPath(url), 'utf8')
        return { format: 'module', shortCircuit: true, source: stripTypes(src) }
      }
      return next(url, context)
    }
    function stripTypes(src) {
      return src
        .replace(/export interface [\\s\\S]*?\\n}\\n/g, '')
        .replace(/export type [^\\n]*\\n/g, '')
        .replace(/: (Theme|ColorTokens)\\b/g, '')
    }
  `), import.meta.url)

const { light, dark, midnight } = await import(
  pathToFileURL(resolve(root, 'packages/core/src/theme/tokens.ts')).href
)

/** bgRaised -> --tg-bg-raised */
const kebab = (k) => k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())

function colorVars(theme, indent = '  ') {
  return Object.entries(theme.colors)
    .map(([k, v]) => `${indent}--tg-${kebab(k)}: ${v};`)
    .join('\n')
}

function scaleVars(theme, indent = '  ') {
  const lines = []
  lines.push(`${indent}--tg-font: ${theme.font.body};`)
  lines.push(`${indent}--tg-font-mono: ${theme.font.mono};`)
  for (const [k, v] of Object.entries(theme.size)) {
    lines.push(`${indent}--tg-text-${k}: ${v / 16}rem;`)
  }
  for (const [k, v] of Object.entries(theme.weight)) {
    lines.push(`${indent}--tg-weight-${k}: ${v};`)
  }
  for (const [k, v] of Object.entries(theme.radius)) {
    lines.push(`${indent}--tg-radius-${k}: ${v}px;`)
  }
  for (const [k, v] of Object.entries(theme.space)) {
    lines.push(`${indent}--tg-space-${k.replace('x', '')}: ${v}px;`)
  }
  return lines.join('\n')
}

const css = `/* GENERATED by scripts/generate-css-tokens.mjs — do not edit.
 * Source of truth: packages/core/src/theme/tokens.ts
 * Regenerate with: npm run tokens
 */

:root {
${colorVars(light)}
${scaleVars(light)}

  --tg-shadow-sm: 0 1px 2px rgb(0 0 0 / 0.06);
  --tg-shadow-md: 0 4px 12px rgb(0 0 0 / 0.08);
  --tg-sidebar-width: 264px;
  --tg-content-max: 1360px;
  --tg-transition: 140ms ease;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(dark, '    ')}

    --tg-shadow-sm: 0 1px 2px rgb(0 0 0 / 0.4);
    --tg-shadow-md: 0 4px 12px rgb(0 0 0 / 0.5);
  }
}

:root[data-theme="dark"] {
${colorVars(dark)}

  --tg-shadow-sm: 0 1px 2px rgb(0 0 0 / 0.4);
  --tg-shadow-md: 0 4px 12px rgb(0 0 0 / 0.5);
}

/* The worked example. Apply with <html data-theme="midnight">. */
:root[data-theme="midnight"] {
${colorVars(midnight)}
${scaleVars(midnight)}

  --tg-shadow-sm: 0 1px 2px rgb(60 40 20 / 0.08);
  --tg-shadow-md: 0 4px 14px rgb(60 40 20 / 0.10);
}
`

const out = resolve(root, 'apps/web/src/theme/tokens.generated.css')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, css)
console.log(`wrote ${out} (${css.split('\n').length} lines)`)
